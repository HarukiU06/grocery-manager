import type { Unit } from '../domain/types';

export interface IngredientConversion {
  /** The countable unit this ingredient is normally counted in. */
  pieceUnit?: Unit;
  /** Weight of one of those pieces, in grams. */
  gramsPerPiece?: number;
  /** Weight of one 15 ml tablespoon, in grams. */
  gramsPerTbsp?: number;
  /** Used for ml, l and cup. */
  densityGPerMl?: number;
}

function piece(gramsPerPiece: number, pieceUnit: Unit = 'pcs'): IngredientConversion {
  return { pieceUnit, gramsPerPiece };
}

function spoon(gramsPerTbsp: number, densityGPerMl: number): IngredientConversion {
  return { gramsPerTbsp, densityGPerMl };
}

